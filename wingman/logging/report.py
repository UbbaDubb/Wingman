"""
Wingman weekly report generator — produces the numbers, tables and PNG charts
that feed the hackathon write-up. Analysis pipeline only, not the write-up.

Run from the repo root:
    python -m wingman.logging.report

Reads every logs/*.jsonl (globbed, so new days are picked up automatically),
tolerates the three record types (cycle / account_snapshot / scheduler skip)
plus known quirks: Monday's records predate gate_hits and the regime gate
(regime_gate is a plain string there), and Tuesday's file contains one stray
pre-wiring stub record with the same string schema — flagged, not fatal.

FRAMING: every P&L figure in this output is UNREALIZED mark-to-market. No
position has ever been closed by the system and all contracts expire
2026-09-18, after the hackathon ends. Nothing here is realized profit.

OUTPUT FILES (all under reports/, regenerated by every run):
  fit_quality.png       sigma1/sigma2/RMSE per cycle, degenerate-fit
                        rejections marked with an x — shows Monday's isolated
                        bad fits vs Tuesday's sustained degeneracy run.
  moneyness.png         moneyness of every proposed trade over time — the
                        upside-wing model artifact appears as a horizontal
                        band around +1.4-2%.
  equity_unrealized.png account equity and total unrealized P&L across the
                        whole week in one continuous plot.
  gate_comparison.png   trades submitted vs cycles rejected per gate type,
                        one bar group per day — the incident (Monday's
                        unbounded duplication) vs the fix (Tuesday's capped
                        exposure), visually.
  smile_evolution_3d.png strike-moneyness x cycle-time x implied-vol mesh —
                        NOT a true volatility surface (Wingman only ever
                        queries one fixed expiry, 2026-09-18 — there is no
                        expiry axis in this data). Degenerate-fit cycles are
                        excluded (their sigma2 values aren't meaningful IVs).

All four 2D x-axes show ONLY market hours (13:30-20:00 UTC) actually present
in the data, with the line broken (not connected) at day boundaries — no dead
space for the closed overnight period. The 3D chart's cycle-time axis uses the
same market-hours compression, applied per day so surfaces never bridge across
a day boundary.
"""

