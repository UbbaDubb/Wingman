def _ts(r):
    return datetime.fromisoformat(r["timestamp"])


def load_days():
    """{date_str: {"cycles": [...], "accounts": [...], "sched": [...],
                   "flagged": [...]}} in chronological order."""
    days = {}
    for path in sorted(LOG_DIR.glob("*.jsonl")):
        day = days.setdefault(path.stem, {"cycles": [], "accounts": [], "sched": [], "flagged": []})
        for lineno, line in enumerate(path.open(encoding="utf-8"), 1):
            line = line.strip()
            if not line:
                continue
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                day["flagged"].append((lineno, "unparseable line"))
                continue
            if r.get("record_type") == "account_snapshot":
                day["accounts"].append(r)
            elif "scheduler" in r:
                day["sched"].append(r)
            elif "timestamp" in r:
                # Known quirk: pre-wiring records carry regime_gate as a plain
                # string. That is every Monday cycle (the gate didn't exist
                # yet) and one stray Tuesday stub; flag the mixed-schema case.
                if isinstance(r.get("regime_gate"), str):
                    r["_pre_gate"] = True
                day["cycles"].append(r)
            else:
                day["flagged"].append((lineno, f"unknown record shape: {list(r)[:4]}"))
    # flag Tuesday-style stubs: a string-schema record in a file where dict
    # records also exist
    for d, day in days.items():
        has_dict = any(isinstance(c.get("regime_gate"), dict) for c in day["cycles"])
        if has_dict:
            for c in day["cycles"]:
                if c.get("_pre_gate"):
                    day["flagged"].append((_ts(c).strftime("%H:%M:%S"),
                                           "pre-wiring stub record (string regime_gate) — excluded from regime stats"))
    return days


def market_hours_axis(day_groups, n_ticks=9):
    """
    Build a compact x-axis with NO dead space for closed-market hours: each
    record gets a sequential integer position (0, 1, 2, ...) in chronological
    order, so overnight/weekend gaps simply don't exist on the axis, matching
    what the scheduler actually produced (it only ever ticks during market
    hours — there is no closed-market data to show a gap for in the first
    place, this just stops matplotlib re-introducing one via a raw datetime
    axis).

    day_groups: list of (day_label, list_of_records) sorted chronologically,
    each record's real timestamp under r["timestamp"].

    Returns:
      id_to_x:    {id(record): x} — look up any record's position, including
                  subsets (e.g. only the degenerate-fit ones) plotted with
                  scatter over a line built from the full set.
      day_segments: [(day_label, [x...], [record...]), ...] — plot ONE line
                  per day using these x/records so the line breaks cleanly at
                  day boundaries instead of connecting across the closed
                  overnight period.
      tick_pos, tick_lab: evenly spaced tick positions and "dd Mon\\nHH:MM"
                  labels sampled from real timestamps, so the compressed axis
                  still reads as wall-clock time.
    """
    id_to_x, day_segments, x = {}, [], 0
    for day_label, recs in day_groups:
        xs = []
        for r in recs:
            id_to_x[id(r)] = x
            xs.append(x)
            x += 1
        if recs:
            day_segments.append((day_label, xs, recs))
    all_recs = [r for _, _, recs in day_segments for r in recs]
    n = len(all_recs)
    if n == 0:
        return id_to_x, day_segments, [], []
    k = min(n_ticks, n)
    idx = sorted({round(i * (n - 1) / max(k - 1, 1)) for i in range(k)})
    tick_pos = [idx_i for idx_i in idx]
    tick_lab = [_ts(all_recs[i]).strftime("%d %b\n%H:%M") for i in idx]
    return id_to_x, day_segments, tick_pos, tick_lab


def _draw_day_boundaries(ax, day_segments):
    """Faint vertical separators between trading days (visual aid only —
    the actual break in each line already happens because each day is a
    separate plot() call, not a connected span)."""
    for day_label, xs, _ in day_segments[1:]:
        ax.axvline(xs[0] - 0.5, color=C_GRAY, lw=0.8, ls=":", alpha=0.5, zorder=1)


def unreal_total(acct_record):
    return sum(p["unrealized_pl"] for p in acct_record.get("positions") or []
               if p.get("unrealized_pl") is not None)


def fit_rmse(cycle):
    """Price-space RMSE from scipy cost: cost = 0.5*sum(res^2) -> sqrt(2c/n)."""
    fit = cycle.get("fit_result")
    n = (cycle.get("snapshot") or {}).get("strikes_used_in_fit")
    if not fit or not n:
        return None
    return math.sqrt(2 * fit["cost"] / n)


def daily_summary(days):
    print("\n== 1. DAILY SUMMARY " + "=" * 58)
    cols = ("date", "cycles", "proposed", "submitted", "spread", "notional",
            "agg-notl", "position", "dir-cflt", "degen", "no-cand",
            "rg full", "rg half", "rg stop",
            "start eq", "end eq", "max unrl", "min unrl")
    rows = []
    for d, day in days.items():
        cycles = day["cycles"]
        proposed = [c for c in cycles if c.get("decision")]
        submitted = [c for c in cycles if c.get("dry_run") is False
                     and (c.get("order_result") or {}).get("response") is not None]
        gh = lambda k: sum((c.get("gate_hits") or {}).get(k, 0) for c in cycles)
        degen = sum(1 for c in cycles if (c.get("fit_result") or {}).get("degenerate_fit"))
        no_cand = sum(1 for c in cycles
                      if c.get("decision") is None and c.get("fit_result")
                      and not c["fit_result"].get("degenerate_fit")
                      and not any((c.get("gate_hits") or {}).values()))
        verdicts = [c["regime_gate"].get("decision") for c in cycles
                    if isinstance(c.get("regime_gate"), dict)]
        accs = day["accounts"]
        unr = [unreal_total(a) for a in accs] or [None]
        eq = [a["account"]["equity"] for a in accs if a.get("account")] or [None]
        fmt = lambda v: f"{v:,.2f}" if isinstance(v, float) else ("-" if v is None else v)
        rows.append((d, len(cycles), len(proposed), len(submitted),
                     gh("spread_gate_hits"), gh("notional_gate_hits"),
                     gh("aggregate_notional_hits"), gh("position_gate_hits"),
                     gh("direction_conflict_hits"), degen, no_cand,
                     verdicts.count("full"), verdicts.count("half"),
                     verdicts.count("stand_down"),
                     fmt(eq[0]), fmt(eq[-1]),
                     fmt(max(unr) if unr[0] is not None else None),
                     fmt(min(unr) if unr[0] is not None else None)))
    widths = [max(len(str(x)) for x in [c] + [r[i] for r in rows]) for i, c in enumerate(cols)]
    print("  " + "  ".join(str(c).rjust(w) for c, w in zip(cols, widths)))
    for r in rows:
        print("  " + "  ".join(str(x).rjust(w) for x, w in zip(r, widths)))
    print("  NOTE: gate-hit counts exist only from 2026-09-01 (gate_hits added then);")
    print("  earlier days show 0 because rejections were printed, not logged.")
    print("  'max/min unrl' are UNREALIZED mark-to-market totals across open positions.")


def _style_axes(*axes):
    for ax in axes:
        ax.spines[["top", "right"]].set_visible(False)
        ax.grid(axis="y", alpha=0.25)


def chart_fit_quality(days):
    day_groups = [(d, [c for c in day["cycles"] if c.get("fit_result")])
                  for d, day in days.items()]
    id_to_x, day_segments, tick_pos, tick_lab = market_hours_axis(day_groups)

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(11, 6.5), sharex=True,
                                   gridspec_kw={"height_ratios": [2, 1]})
    for i, (day_label, xs, recs) in enumerate(day_segments):
        lab1 = "sigma2 (stress component)" if i == 0 else None
        lab2 = "sigma1 (calm component)" if i == 0 else None
        lab3 = "fit RMSE (price space)" if i == 0 else None
        ax1.plot(xs, [c["fit_result"]["sigma2"] for c in recs], color=C_AMBER, lw=2, label=lab1)
        ax1.plot(xs, [c["fit_result"]["sigma1"] for c in recs], color=C_BLUE, lw=2, label=lab2)
        ax2.plot(xs, [fit_rmse(c) for c in recs], color=C_TEAL, lw=2, label=lab3)

    degen = [c for _, _, recs in day_segments for c in recs if c["fit_result"].get("degenerate_fit")]
    if degen:
        ax1.scatter([id_to_x[id(c)] for c in degen], [c["fit_result"]["sigma2"] for c in degen],
                    marker="x", s=80, linewidths=2.2, color=C_RED, zorder=5,
                    label=f"rejected by degenerate-fit guard (n={len(degen)})")

    ax1.axhspan(0.05, 1.0, color=C_TEAL, alpha=0.10, zorder=0)
    ax1.annotate("plausible SPY vol band  [0.05, 1.0]\n(fits outside this are rejected, not traded)",
                xy=(0.01, 0.5), xycoords="axes fraction", fontsize=9.5,
                color="#0d5c54", fontweight="bold", va="center",
                bbox=dict(boxstyle="round,pad=0.3", fc="white", ec="none", alpha=0.75))
    ax1.set_ylabel("fitted vol")
    ax1.legend(loc="upper left", frameon=False)
    ax2.set_ylabel("RMSE ($)")
    ax2.legend(loc="upper left", frameon=False)
    _style_axes(ax1, ax2)
    _draw_day_boundaries(ax1, day_segments)
    _draw_day_boundaries(ax2, day_segments)
    ax2.set_xticks(tick_pos)
    ax2.set_xticklabels(tick_lab)
    ax2.set_xlim(-0.5, max(tick_pos) + 0.5 if tick_pos else 1)
    fig.suptitle("Mixture fit quality per cycle — market hours only, degenerate fits marked")
    fig.tight_layout()
    out = REPORT_DIR / "fit_quality.png"
    fig.savefig(out, dpi=150)
    plt.close(fig)
    return out


