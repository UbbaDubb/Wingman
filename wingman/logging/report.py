def chart_gate_comparison(days):
    """Trades submitted vs cycles rejected per gate, one bar group per day.
    Seven series: submitted, spread, per-trade notional, aggregate-notional
    (whole-book cap), per-leg position, direction-conflict, degenerate-fit.
    The aggregate-notional and direction-conflict keys were added 2026-09-02;
    older records store 0 for those keys (their fires were counted under the
    parent category in the now-fixed older code)."""
    dates = list(days.keys())
    submitted, spread, notional, agg_notional, position, dir_conflict, degen = (
        [], [], [], [], [], [], []
    )
    for d in dates:
        cycles = days[d]["cycles"]
        gh = lambda k: sum((c.get("gate_hits") or {}).get(k, 0) for c in cycles)
        submitted.append(sum(1 for c in cycles if c.get("dry_run") is False
                             and (c.get("order_result") or {}).get("response") is not None))
        spread.append(gh("spread_gate_hits"))
        notional.append(gh("notional_gate_hits"))
        agg_notional.append(gh("aggregate_notional_hits"))
        position.append(gh("position_gate_hits"))
        dir_conflict.append(gh("direction_conflict_hits"))
        degen.append(sum(1 for c in cycles if (c.get("fit_result") or {}).get("degenerate_fit")))

    C_GREEN = "#15803d"
    C_PINK  = "#be185d"
    series = [
        ("trades submitted",            submitted,    C_BLUE),
        ("spread gate hits",            spread,       C_AMBER),
        ("per-trade notional cap",      notional,     C_TEAL),
        ("aggregate notional cap",      agg_notional, C_GREEN),
        ("position cap (per-leg)",      position,     C_PURPLE),
        ("direction-conflict guard",    dir_conflict, C_PINK),
        ("degenerate-fit rejections",   degen,        C_RED),
    ]
    n = len(series)
    x = list(range(len(dates)))
    width = 0.8 / n

    fig, ax = plt.subplots(figsize=(11, 5.5))
    for i, (label, values, color) in enumerate(series):
        offs = [xi + (i - (n - 1) / 2) * width for xi in x]
        bars = ax.bar(offs, values, width=width * 0.92, color=color, label=label,
                      edgecolor="white", linewidth=0.6)
        ax.bar_label(bars, fontsize=8, color="#374151", padding=2)
    ax.set_xticks(x)
    ax.set_xticklabels(dates)
    ax.set_ylabel("count")
    ax.set_title(
        "Trades submitted vs gate rejections, per day\n"
        "aggregate-notional & direction-conflict keys added 2026-09-02 "
        "(older logs stored those fires in parent categories)"
    )
    ax.legend(loc="upper left", frameon=False, ncols=2, fontsize=8.5)
    _style_axes(ax)
    fig.tight_layout()
    out = REPORT_DIR / "gate_comparison.png"
    fig.savefig(out, dpi=150)
    plt.close(fig)
    return out


def _load_snapshot_index():
    """{embedded snapshot timestamp: parsed snapshot dict}, built once from
    every file in snapshots/. Cycle records only log 'live' as their source
    (not a file path) for scheduler-driven ticks, so this is how a cycle's
    logged fit gets reconnected to the full per-strike quotes it was fit
    against — matched via the timestamp embedded in both places, which is
    generated once per fetch and so is exact, not approximate."""
    index = {}
    for f in SNAP_DIR.glob("*.json"):
        try:
            snap = json.loads(f.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        if snap.get("timestamp"):
            index[snap["timestamp"]] = snap
    return index


def _clean_cycles_with_snapshot(days, snap_index):
    """
    {day_label: [cycle, ...]} for cycles whose fit succeeded, cleared the
    degenerate-fit guard, AND were matched to their full snapshot (attached
    as cycle['_full_snapshot']). Shared by every chart that needs the raw
    per-strike quotes a cycle was fit against — the 3D smile-evolution mesh
    and the by-day smile overlay both build on this exact same filtering, so
    "clean cycle" means the same thing in both places.
    """
    out = {}
    for d, day in days.items():
        lst = []
        for c in day["cycles"]:
            fit = c.get("fit_result")
            if not fit or fit.get("degenerate_fit") or not fit.get("success", True):
                continue
            snap = snap_index.get((c.get("snapshot") or {}).get("timestamp"))
            if snap is None:
                continue
            c["_full_snapshot"] = snap
            lst.append(c)
        if lst:
            out[d] = lst
    return out


def chart_smile_evolution_3d(days):
    """
    Strike-moneyness x cycle-time x implied-vol mesh across every cycle whose
    fit succeeded and cleared the degenerate-fit guard.

    NOT a volatility surface: Wingman only ever queries a single fixed expiry
    (2026-09-18), so there is no expiry axis in this data — the title and
    z-label say so explicitly and this docstring repeats it so the framing
    survives any refactor.

    DATA CHOICE: uses plot_trisurf on the raw, irregular (moneyness, cycle,
    IV) points rather than interpolating onto a common moneyness grid — the
    live OI filter shifts the liquid strike range cycle to cycle, and
    trisurf's Delaunay triangulation handles that natively without smoothing
    over exactly what was measured. Chosen for honesty about the raw data
    over a smoother but partly-synthetic interpolated surface.
    """
    from wingman.models.fit_utils import call_equivalent_quote, implied_vol_call

    snap_index = _load_snapshot_index()
    n_all_fit = sum(1 for day in days.values() for c in day["cycles"] if c.get("fit_result"))
    day_groups = list(_clean_cycles_with_snapshot(days, snap_index).items())
    id_to_x, day_segments, tick_pos, tick_lab = market_hours_axis(day_groups)
    n_used = sum(len(recs) for _, _, recs in day_segments)
    n_excluded = n_all_fit - n_used

    # Per-day point clouds (kept separate so the triangulation never bridges
    # across a day boundary — same principle as the 2D charts' per-day lines).
    day_points, all_iv = [], []
    for day_label, xs, cycles in day_segments:
        mny, ys, ivs = [], [], []
        for x, c in zip(xs, cycles):
            snap = c["_full_snapshot"]
            fit = c["fit_result"]
            forward, tte, r = fit["forward"], fit["tte"], fit.get("r", 0.0)
            spot = snap["spot"]
            for row in snap.get("strikes", []):
                q = call_equivalent_quote(row, spot, forward, tte, r)
                if q is None:
                    continue
                iv = implied_vol_call(q["mid"], forward, row["strike"], tte, r)
                if iv is None:
                    continue
                mny.append((row["strike"] / spot - 1.0) * 100)
                ys.append(x)
                ivs.append(iv)
        if len(set(ys)) >= 2:  # trisurf needs >1 distinct y per day to triangulate
            day_points.append((day_label, mny, ys, ivs))
            all_iv.extend(ivs)

    if not day_points:
        print("[chart_smile_evolution_3d] no usable cycles — skipping")
        return None

    norm = Normalize(vmin=min(all_iv), vmax=max(all_iv))
    cmap = plt.get_cmap("viridis")

    fig = plt.figure(figsize=(12.5, 9))
    ax = fig.add_subplot(111, projection="3d")
    for day_label, mny, ys, ivs in day_points:
        ax.plot_trisurf(mny, ys, ivs, cmap=cmap, norm=norm, linewidth=0.15,
                        edgecolor="white", antialiased=True, shade=True, alpha=0.97)
    ax.set_xlabel("moneyness: (strike/spot − 1) x 100, %", labelpad=16)
    ax.set_ylabel("cycle (market hours only)", labelpad=14)
    ax.set_zlabel("implied vol", labelpad=8)
    ax.tick_params(axis="x", pad=2)
    ax.set_yticks(tick_pos)
